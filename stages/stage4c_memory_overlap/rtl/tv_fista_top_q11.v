`timescale 1ns / 1ps
// -----------------------------------------------------------------------------
// Stage-3: 64x64 Q5.11 TV-FISTA top-level compute IP (PL-only datapath).
//
// Input: 1024 signed S32.F11 measurements, packed by ascending row-major mask
//        index. The measurement mask is fixed to Stage-0.2 low-sequency mask.
// Output: 4096 signed Q5.11 pixels, clipped to [0, 2048] only at final readout.
//
// Algorithm exactly follows stage0_2_fixedpoint.py:
//   x0 = z0 = W^T y, W=H_4096/64
//   v  = z - W^T P_Omega^T(P_Omega Wz - y)
//   x' = TVProx_35(v)
//   z' = x' + (((x' - x) * beta_q15[k]) >>> 15)
//   repeat OUTER_ITERS (default 40), then clip x to [0,2048].
//
// beta_q15 is the precomputed 40-entry UQ0.15 ROM generated by Stage-0.2.
// One FWHT core is reused inside data_consistency_fista_q11 for init, forward,
// and adjoint transforms. Stage-1 TV Prox and Stage-2B arithmetic are reused.
// The original Stage-1/Stage-2B projects are not modified.
// -----------------------------------------------------------------------------
module tv_fista_top_q11 #(
    parameter integer OUTER_ITERS = 40,
    parameter integer TV_INNER_STEPS = 35
) (
    input wire clk,
    input wire rst_n,

    // Load exactly 1024 packed measurements in ascending mask-index order.
    input wire meas_load_we,
    input wire [9:0] meas_load_addr,
    input wire signed [31:0] meas_load_data,
    output wire meas_load_ready,

    // Start after all 1024 measurements have been loaded.
    input wire start,
    output wire ready,
    output wire busy,
    output reg done,
    output reg range_error,
    output reg protocol_error,
    output reg [5:0] outer_iter,

    // Synchronous final image read port. Output is clipped to [0,2048].
    input wire result_read_en,
    input wire [11:0] result_read_addr,
    output reg result_read_valid,
    output wire signed [15:0] result_read_data
);
    localparam [4:0]
        S_IDLE             = 5'd0,
        S_INIT_START       = 5'd1,
        S_INIT_WAIT        = 5'd2,
        S_INIT_READ        = 5'd3,
        S_INIT_CAPTURE     = 5'd4,
        S_INIT_WRITE       = 5'd5,
        S_DC_LOAD_READ     = 5'd6,
        S_DC_LOAD_CAPTURE  = 5'd7,
        S_DC_LOAD_WRITE    = 5'd8,
        S_DC_START         = 5'd9,
        S_DC_WAIT          = 5'd10,
        S_DC_OUT_READ      = 5'd11,
        S_DC_OUT_CAPTURE   = 5'd12,
        S_TV_LOAD_WRITE    = 5'd13,
        S_TV_START         = 5'd14,
        S_TV_WAIT          = 5'd15,
        S_UPDATE_READ      = 5'd16,
        S_UPDATE_CAPTURE   = 5'd17,
        S_UPDATE_CALC      = 5'd18,
        S_UPDATE_WRITE     = 5'd19,
        S_FINISH           = 5'd20,
        S_ERROR            = 5'd21;

    reg [4:0] state;
    reg [11:0] scan_addr;
    reg [10:0] measurement_count;
    reg completed;

    reg signed [15:0] transfer_hold;
    reg signed [15:0] z_load_hold;
    reg signed [15:0] tv_new_hold;
    reg signed [15:0] x_old_hold;
    reg signed [15:0] z_next_hold;

    // FISTA state memories. Single-port synchronous BRAM-friendly access:
    // x_mem is read during update/readout and written during init/update;
    // z_mem is read during DC loading and written during init/update.
    (* ram_style = "block" *) reg signed [15:0] x_mem [0:4095];
    (* ram_style = "block" *) reg signed [15:0] z_mem [0:4095];
    reg signed [15:0] z_mem_rdata;
    reg signed [15:0] x_mem_rdata;

    // Precomputed beta_k = (t_(k-1)-1)/t_k, unsigned Q0.15.
    reg [15:0] beta_rom [0:39];
    initial $readmemh("fista_beta_q15.hex", beta_rom);

    wire signed [16:0] momentum_diff =
        $signed({tv_new_hold[15], tv_new_hold}) -
        $signed({x_old_hold[15], x_old_hold});
    // Explicitly widen both operands before multiplication. This avoids any
    // Verilog expression-width truncation and preserves the full signed product.
    wire signed [33:0] momentum_diff_ext = {{17{momentum_diff[16]}}, momentum_diff};
    wire signed [33:0] beta_ext = {18'd0, beta_rom[outer_iter]};
    wire signed [33:0] momentum_product = momentum_diff_ext * beta_ext;
    wire signed [33:0] momentum_delta = momentum_product >>> 15;
    wire signed [33:0] tv_new_ext = {{18{tv_new_hold[15]}}, tv_new_hold};
    wire signed [33:0] z_next_wide = tv_new_ext + momentum_delta;

    // Stage-3 data-consistency engine: Stage-2B plus exact W^T*y initialization.
    reg dc_init_start;
    reg dc_start;
    wire dc_ready, dc_busy, dc_done, dc_range_error;
    reg dc_load_we, dc_load_kind;
    reg [11:0] dc_load_addr;
    reg signed [31:0] dc_load_data;
    reg dc_read_en;
    reg [11:0] dc_read_addr;
    wire dc_read_valid;
    wire signed [15:0] dc_read_data;

    data_consistency_fista_q11 u_data_consistency (
        .clk(clk), .rst_n(rst_n),
        .start(dc_start), .init_start(dc_init_start),
        .ready(dc_ready), .busy(dc_busy), .done(dc_done),
        .range_error(dc_range_error),
        .load_we(dc_load_we), .load_kind(dc_load_kind),
        .load_addr(dc_load_addr), .load_data(dc_load_data),
        .read_en(dc_read_en), .read_addr(dc_read_addr),
        .read_valid(dc_read_valid), .read_data(dc_read_data)
    );

    // Stage-1 TV Prox engine, 35 Jacobi dual iterations by default.
    reg tv_load_we;
    reg [11:0] tv_load_addr;
    reg signed [15:0] tv_load_data;
    reg tv_start;
    wire tv_ready, tv_busy, tv_done;
    reg tv_read_en;
    reg [11:0] tv_read_addr;
    wire tv_read_valid;
    wire signed [15:0] tv_read_data;

    tv_prox64_bram_q11 #(.INNER_STEPS(TV_INNER_STEPS)) u_tv_prox (
        .clk(clk), .rst_n(rst_n),
        .load_we(tv_load_we), .load_addr(tv_load_addr), .load_data(tv_load_data),
        .start(tv_start), .ready(tv_ready), .busy(tv_busy), .done(tv_done),
        .read_en(tv_read_en), .read_addr(tv_read_addr),
        .read_valid(tv_read_valid), .read_data(tv_read_data)
    );

    assign meas_load_ready = (state == S_IDLE) &&
                             (measurement_count < 11'd1024) &&
                             !protocol_error && !range_error;
    assign ready = (state == S_IDLE) &&
                   (measurement_count == 11'd1024) &&
                   !protocol_error && !range_error;
    assign busy = (state != S_IDLE) && (state != S_ERROR);

    // Top-level control outputs to the child engines.
    always @* begin
        dc_init_start = (state == S_INIT_START);
        dc_start = (state == S_DC_START);

        dc_load_we = 1'b0;
        dc_load_kind = 1'b0;
        dc_load_addr = scan_addr;
        dc_load_data = {{16{z_load_hold[15]}}, z_load_hold};
        if ((state == S_IDLE) && meas_load_we && meas_load_ready &&
            (meas_load_addr == measurement_count[9:0])) begin
            dc_load_we = 1'b1;
            dc_load_kind = 1'b1;
            dc_load_addr = {2'b00, meas_load_addr};
            dc_load_data = meas_load_data;
        end else if (state == S_DC_LOAD_WRITE) begin
            dc_load_we = 1'b1;
            dc_load_kind = 1'b0;
            dc_load_addr = scan_addr;
            dc_load_data = {{16{z_load_hold[15]}}, z_load_hold};
        end

        dc_read_en = (state == S_INIT_READ) || (state == S_DC_OUT_READ);
        dc_read_addr = scan_addr;

        tv_load_we = (state == S_TV_LOAD_WRITE);
        tv_load_addr = scan_addr;
        tv_load_data = transfer_hold;
        tv_start = (state == S_TV_START);
        tv_read_en = (state == S_UPDATE_READ);
        tv_read_addr = scan_addr;
    end

    // Synchronous FISTA state-memory ports.
    always @(posedge clk) begin
        if (state == S_INIT_WRITE) begin
            x_mem[scan_addr] <= transfer_hold;
            z_mem[scan_addr] <= transfer_hold;
        end else if (state == S_UPDATE_WRITE) begin
            x_mem[scan_addr] <= tv_new_hold;
            z_mem[scan_addr] <= z_next_hold;
        end

        if (state == S_DC_LOAD_READ)
            z_mem_rdata <= z_mem[scan_addr];

        if (state == S_UPDATE_READ)
            x_mem_rdata <= x_mem[scan_addr];
        else if ((state == S_IDLE) && completed && result_read_en)
            x_mem_rdata <= x_mem[result_read_addr];
    end

    // Result is clipped only at final readout, matching the Stage-0.2 model.
    wire signed [15:0] x_read_signed = x_mem_rdata;
    assign result_read_data =
        (x_read_signed < 16'sd0) ? 16'sd0 :
        (x_read_signed > 16'sd2048) ? 16'sd2048 : x_read_signed;

    always @(posedge clk) begin
        if (!rst_n)
            result_read_valid <= 1'b0;
        else
            result_read_valid <= ((state == S_IDLE) && completed && result_read_en);
    end

    always @(posedge clk) begin
        if (!rst_n) begin
            state <= S_IDLE;
            scan_addr <= 12'd0;
            measurement_count <= 11'd0;
            outer_iter <= 6'd0;
            transfer_hold <= 16'sd0;
            z_load_hold <= 16'sd0;
            tv_new_hold <= 16'sd0;
            x_old_hold <= 16'sd0;
            z_next_hold <= 16'sd0;
            completed <= 1'b0;
            done <= 1'b0;
            range_error <= 1'b0;
            protocol_error <= 1'b0;
        end else begin
            done <= 1'b0;
            case (state)
                S_IDLE: begin
                    if (meas_load_we && meas_load_ready) begin
                        if (meas_load_addr == measurement_count[9:0])
                            measurement_count <= measurement_count + 11'd1;
                        else
                            protocol_error <= 1'b1;
                    end else if (start) begin
                        if (ready && dc_ready && tv_ready) begin
                            completed <= 1'b0;
                            range_error <= 1'b0;
                            outer_iter <= 6'd0;
                            scan_addr <= 12'd0;
                            state <= S_INIT_START;
                        end else begin
                            protocol_error <= 1'b1;
                        end
                    end
                end

                // Compute exact initial backprojection x0=z0=W^T*y.
                S_INIT_START: state <= S_INIT_WAIT;
                S_INIT_WAIT: begin
                    if (dc_done) begin
                        if (dc_range_error) begin
                            range_error <= 1'b1;
                            state <= S_ERROR;
                        end else begin
                            scan_addr <= 12'd0;
                            state <= S_INIT_READ;
                        end
                    end
                end
                S_INIT_READ: state <= S_INIT_CAPTURE;
                S_INIT_CAPTURE: begin
                    if (dc_read_valid) begin
                        transfer_hold <= dc_read_data;
                        state <= S_INIT_WRITE;
                    end
                end
                S_INIT_WRITE: begin
                    if (scan_addr == 12'd4095) begin
                        scan_addr <= 12'd0;
                        state <= S_DC_LOAD_READ;
                    end else begin
                        scan_addr <= scan_addr + 12'd1;
                        state <= S_INIT_READ;
                    end
                end

                // Load current extrapolated state z into Stage-2B's z/ FWHT RAM.
                S_DC_LOAD_READ: state <= S_DC_LOAD_CAPTURE;
                S_DC_LOAD_CAPTURE: begin
                    z_load_hold <= z_mem_rdata;
                    state <= S_DC_LOAD_WRITE;
                end
                S_DC_LOAD_WRITE: begin
                    if (scan_addr == 12'd4095) begin
                        scan_addr <= 12'd0;
                        state <= S_DC_START;
                    end else begin
                        scan_addr <= scan_addr + 12'd1;
                        state <= S_DC_LOAD_READ;
                    end
                end
                S_DC_START: state <= S_DC_WAIT;
                S_DC_WAIT: begin
                    if (dc_done) begin
                        if (dc_range_error) begin
                            range_error <= 1'b1;
                            state <= S_ERROR;
                        end else begin
                            scan_addr <= 12'd0;
                            state <= S_DC_OUT_READ;
                        end
                    end
                end

                // Stream data-consistency output v into TV Prox input f.
                S_DC_OUT_READ: state <= S_DC_OUT_CAPTURE;
                S_DC_OUT_CAPTURE: begin
                    if (dc_read_valid) begin
                        transfer_hold <= dc_read_data;
                        state <= S_TV_LOAD_WRITE;
                    end
                end
                S_TV_LOAD_WRITE: begin
                    if (scan_addr == 12'd4095) begin
                        scan_addr <= 12'd0;
                        state <= S_TV_START;
                    end else begin
                        scan_addr <= scan_addr + 12'd1;
                        state <= S_DC_OUT_READ;
                    end
                end
                S_TV_START: state <= S_TV_WAIT;
                S_TV_WAIT: begin
                    if (tv_done) begin
                        scan_addr <= 12'd0;
                        state <= S_UPDATE_READ;
                    end
                end

                // Read x_new from TV Prox and x_old from x_mem, then calculate
                // z_new = x_new + (((x_new-x_old)*beta_q15[k]) >>> 15).
                S_UPDATE_READ: state <= S_UPDATE_CAPTURE;
                S_UPDATE_CAPTURE: begin
                    if (tv_read_valid) begin
                        tv_new_hold <= tv_read_data;
                        x_old_hold <= x_mem_rdata;
                        state <= S_UPDATE_CALC;
                    end
                end
                S_UPDATE_CALC: begin
                    if (z_next_wide > 34'sd32767 || z_next_wide < -34'sd32768) begin
                        range_error <= 1'b1;
                        state <= S_ERROR;
                    end else begin
                        z_next_hold <= z_next_wide[15:0];
                        state <= S_UPDATE_WRITE;
                    end
                end
                S_UPDATE_WRITE: begin
                    if (scan_addr == 12'd4095) begin
                        scan_addr <= 12'd0;
                        if (outer_iter == OUTER_ITERS - 1) begin
                            state <= S_FINISH;
                        end else begin
                            outer_iter <= outer_iter + 6'd1;
                            state <= S_DC_LOAD_READ;
                        end
                    end else begin
                        scan_addr <= scan_addr + 12'd1;
                        state <= S_UPDATE_READ;
                    end
                end

                S_FINISH: begin
                    done <= 1'b1;
                    completed <= 1'b1;
                    state <= S_IDLE;
                end
                S_ERROR: state <= S_ERROR;
                default: state <= S_ERROR;
            endcase
        end
    end

endmodule
